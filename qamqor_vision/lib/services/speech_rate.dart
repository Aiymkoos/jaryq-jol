/// Скорость синтеза речи.
///
/// Три ступени вместо ползунка: ползунок нужно вести пальцем и видеть,
/// куда он доехал. Кнопка, перебирающая три значения по кругу и называющая
/// выбранное вслух, работает вслепую.
///
/// Вынесено в отдельный файл, потому что нужно и службе речи, и настройкам,
/// и строкам интерфейса — иначе они начали бы импортировать друг друга по кругу.
enum SpeechRate {
  slow(0.32),
  normal(0.45),
  // Опытные пользователи скринридеров слушают заметно быстрее обычной речи;
  // медленный голос их утомляет.
  fast(0.62);

  const SpeechRate(this.value);

  /// Значение для `flutter_tts`.
  final double value;

  SpeechRate get next => switch (this) {
    SpeechRate.slow => SpeechRate.normal,
    SpeechRate.normal => SpeechRate.fast,
    SpeechRate.fast => SpeechRate.slow,
  };
}
